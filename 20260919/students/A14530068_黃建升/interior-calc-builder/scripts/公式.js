/* 值落在合理範圍外時，試試看是不是用了別的單位的數字。
   例：窗寬欄位要公分，使用者填 3（心裡想的是 3 公尺），
   3 × 100 = 300 落回合理範圍 → 幾乎可以確定是單位填錯。 */
function 單位疑慮(d, v) {
  if (!d.合理 || v === 0) { return null; }
  if (v >= d.合理[0] && v <= d.合理[1]) { return null; }

  var 候選 = (常見誤填[d.單位] || []);
  for (var i = 0; i < 候選.length; i++) {
    var 換 = v * 候選[i].倍;
    if (換 >= d.合理[0] && 換 <= d.合理[1]) {
      return d.名 + ' ' + v + ' ' + (d.單位 || '') +
             ' 超出常見範圍；若這是' + 候選[i].來源 + '的數字，應填 ' +
             (Math.round(換 * 1000) / 1000) + ' ' + (d.單位 || '');
    }
  }
  return d.名 + ' ' + v + ' ' + (d.單位 || '') + ' 超出常見範圍（' +
         d.合理[0] + '～' + d.合理[1] + '），請確認沒有填錯';
}

/* 錯誤物件一律是 { 欄位, 等級, 訊息 }。
   帶欄位名才能在畫面上標到出錯的那一格——只給訊息字串的話，
   使用者要自己從七個輸入欄猜是哪一個，手機上尤其痛苦。
   等級：錯誤＝算不出來或結果無意義，擋住；提醒＝算得出來但可疑，照常顯示；
         致命＝工具本身壞了，不要假裝還能用。 */
function 錯(欄位, 訊息) { return { 欄位: 欄位, 等級: '錯誤', 訊息: 訊息 }; }
function 提(欄位, 訊息) { return { 欄位: 欄位, 等級: '提醒', 訊息: 訊息 }; }

function 驗證(名稱, i) {
  var 出 = [];
  var r = 規則[名稱] || {};
  Object.keys(r).forEach(function (k) {
    var v = i[k];
    var d = r[k];
    if (typeof v !== 'number' || !isFinite(v)) {
      出.push(錯(k, d.名 + '要填數字'));
      return;
    }
    if (typeof d.大於 === 'number' && !(v > d.大於)) {
      出.push(錯(k, d.名 + '必須大於 ' + d.大於));
    }
    if (typeof d.最小 === 'number' && v < d.最小) {
      出.push(錯(k, d.名 + '不能小於 ' + d.最小));
    }
    if (typeof d.最大 === 'number' && v > d.最大) {
      出.push(錯(k, d.名 + '不能大於 ' + d.最大));
    }
    if (d.整數 && Math.floor(v) !== v) {
      出.push(錯(k, d.名 + '必須是整數'));
    }
    if (d.零提醒 && v === 0) {
      出.push(提(k, d.零提醒));
    }
    /* 已經有錯誤的欄位就不要再疊單位提醒，訊息會互相打架 */
    var 已有錯 = 出.some(function (e) { return e.欄位 === k && e.等級 === '錯誤'; });
    if (!已有錯) {
      var 疑 = 單位疑慮(d, v);
      if (疑) { 出.push(提(k, 疑)); }
    }
  });
  return 出;
}

