/* 計算引擎：所有計算機共用這一份。Node 與瀏覽器都能跑。
   新增計算類型時只改這裡，不要在個別 HTML 裡另外寫公式。
   契約：計算(名稱, 輸入物件) → { 過程:[{標籤,算式}], 值:{數字...}, 註記:字串 } */
'use strict';

var 換算 = {
  坪: 3.305785,
  台尺: 30.3,
  台寸: 3.03,
  才: 0.091809,
  碼: 91.44,
  英吋: 2.54,
  加侖: 3.785
};

var 插座建議表 = {
  客廳: [6, 8], 主臥: [4, 6], 次臥: [4, 4],
  廚房: [5, 7], 衛浴: [1, 2], 書房: [4, 6]
};

function n2(v) { return (Math.round(v * 100) / 100).toFixed(2); }

var 公式 = {
  油漆: {
    說明: '乳膠漆用量，輸出建議購買加侖數',
    計算: function (i) {
      var 地坪m2 = i.ping * 換算.坪;
      var 由坪數推估 = !(i.perim > 0);
      var 周長 = 由坪數推估 ? Math.sqrt(地坪m2) * 4 : i.perim;
      var 牆面積 = 周長 * i.wallH - i.openArea;
      if (牆面積 < 0) { 牆面積 = 0; }
      var 塗佈需求 = 牆面積 * i.coats;
      var 公升 = 塗佈需求 / i.rate * (1 + i.loss / 100);
      var 加侖數 = Math.ceil(公升 / 換算.加侖);

      var 過程 = [];
      if (由坪數推估) {
        過程.push({ 標籤: '地坪換算', 算式: i.ping + ' 坪 × 3.3058 = ' + n2(地坪m2) + ' m²' });
        過程.push({ 標籤: '推估周長', 算式: '√' + n2(地坪m2) + ' × 4 = ' + n2(周長) + ' m' });
      } else {
        過程.push({ 標籤: '牆面周長（實測）', 算式: n2(周長) + ' m' });
      }
      過程.push({ 標籤: '牆面積', 算式: n2(周長) + ' × ' + i.wallH + ' − ' + i.openArea + ' = ' + n2(牆面積) + ' m²' });
      過程.push({ 標籤: '塗佈需求（' + i.coats + ' 道）', 算式: n2(塗佈需求) + ' m²' });
      過程.push({ 標籤: '需求量（含損耗 ' + i.loss + '%）', 算式: n2(公升) + ' L' });

      return {
        過程: 過程,
        值: { 地坪m2: 地坪m2, 周長: 周長, 牆面積: 牆面積, 塗佈需求: 塗佈需求, 公升: 公升, 加侖數: 加侖數 },
        註記: 由坪數推估
          ? '假設：房間為正方形。長寬相差大的空間會低估，建議實測周長填入。'
          : '使用實測周長，未套用正方形假設。'
      };
    }
  },

  窗簾: {
    說明: '直式用布的窗簾布量，輸出建議下單碼數',
    計算: function (i) {
      var 布寬需求 = i.窗寬 * i.倍數 + i.兩側收邊;
      var 幅數 = Math.ceil(布寬需求 / i.幅寬);
      var 單幅長度 = i.窗高 + i.上下摺邊;
      var 總碼數 = 幅數 * 單幅長度 / 換算.碼;
      var 建議碼數 = Math.ceil(總碼數);

      return {
        過程: [
          { 標籤: '布寬需求', 算式: i.窗寬 + ' × ' + i.倍數 + ' + ' + i.兩側收邊 + ' = ' + n2(布寬需求) + ' cm' },
          { 標籤: '用布幅數', 算式: '進位(' + n2(布寬需求) + ' ÷ ' + i.幅寬 + ') = ' + 幅數 + ' 幅' },
          { 標籤: '單幅長度', 算式: i.窗高 + ' + ' + i.上下摺邊 + ' = ' + 單幅長度 + ' cm' },
          { 標籤: '總長度', 算式: 幅數 + ' × ' + 單幅長度 + ' ÷ 91.44 = ' + n2(總碼數) + ' 碼' }
        ],
        值: { 布寬需求: 布寬需求, 幅數: 幅數, 單幅長度: 單幅長度, 總碼數: 總碼數, 建議碼數: 建議碼數 },
        註記: '直式用布（布幅垂直）。素色布橫用是另一套算法，本公式不適用；對花布需另加花距。'
      };
    }
  },

  磁磚: {
    說明: '磁磚片數與箱數',
    計算: function (i) {
      var 鋪貼面積 = i.長 * i.寬 - i.扣除;
      if (鋪貼面積 < 0) { 鋪貼面積 = 0; }
      var 單片面積 = ((i.磚長 + i.填縫 / 10) / 100) * ((i.磚寬 + i.填縫 / 10) / 100);
      var 片數 = Math.ceil(鋪貼面積 / 單片面積 * (1 + i.損耗 / 100));
      var 箱數 = Math.ceil(片數 / i.每箱片數);

      return {
        過程: [
          { 標籤: '鋪貼面積', 算式: i.長 + ' × ' + i.寬 + ' − ' + i.扣除 + ' = ' + n2(鋪貼面積) + ' m²' },
          { 標籤: '單片面積（含填縫 ' + i.填縫 + ' mm）', 算式: n2(單片面積 * 10000) + ' cm²' },
          { 標籤: '片數（含損耗 ' + i.損耗 + '%）', 算式: 片數 + ' 片' }
        ],
        值: { 鋪貼面積: 鋪貼面積, 單片面積: 單片面積, 片數: 片數, 箱數: 箱數 },
        註記: '每箱片數各廠牌不同，一定要向廠商確認後填入。'
      };
    }
  }
};

function 計算(名稱, 輸入) {
  if (!公式[名稱]) { throw new Error('沒有這個公式：' + 名稱); }
  return 公式[名稱].計算(輸入);
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = { 換算: 換算, 公式: 公式, 計算: 計算, 插座建議表: 插座建議表 };
}
