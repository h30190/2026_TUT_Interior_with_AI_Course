function 計算(名稱, 輸入) {
  if (!公式[名稱]) { throw new Error('沒有這個公式：' + 名稱); }
  var 錯誤 = 驗證(名稱, 輸入);
  if (錯誤.length) {
    return { 過程: [], 值: {}, 註記: '', 錯誤: 錯誤 };
  }
  var r = 公式[名稱].計算(輸入);
  r.錯誤 = [];
  return r;
}

