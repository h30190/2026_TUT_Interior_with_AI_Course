/* 兩位小數的顯示。
   2026-10-03 王品洋交叉稽核 #6：原本是 (Math.round(v * 100) / 100).toFixed(2)，
   v 超過約 1.8e306 時「v × 100」先溢位，數值本身有限、顯示字串卻是 Infinity——
   出口關卡只看數值，於是畫面寫著 Infinity m² 還照常給結果。
   顯示函式自己不准製造 Infinity：大到不適合兩位小數的值改用有效位數。 */
function n2(v) {
  if (typeof v !== 'number' || !isFinite(v)) { return String(v); }
  if (Math.abs(v) >= 1e15) { return v.toPrecision(6); }
  return (Math.round(v * 100) / 100).toFixed(2);
}

/* 把「使用者輸入的原值」放進計算過程時用。
   2026-10-03 王品洋交叉稽核 #5：台尺 9.24 換成公尺是 2.8000000000000003，
   原本直接串進算式字串，畫面就出現這串浮點雜訊。
   取 12 位有效數字再轉回數字：雜訊消失，使用者真的填的小數位一位不少。 */
function 顯(v) {
  if (typeof v !== 'number' || !isFinite(v)) { return String(v); }
  return String(Number(v.toPrecision(12)));
}

/* 進位前先消掉二進位浮點的雜訊。
   2026-10-03 稽核同學工具時照出我自己同樣的 bug：
   100 × 1.1 在浮點下是 110.00000000000001，直接 Math.ceil 會得到 111，
   使用者就多買一箱磁磚。而且中間值顯示時會被四捨五入成 110，
   畫面上看起來完全正確，bug 的證據被顯示邏輯藏起來。

   一律用這支取代 Math.ceil。不要改成減一個固定的 epsilon——
   那會讓真正需要進位的小數（例如 110.0000001 片確實不夠）被誤判成不用進位。
   這裡只抹掉第 9 位小數之後的雜訊，實際的小數差距都比那大得多。 */
function 進位(v) {
  if (typeof v !== 'number' || !isFinite(v)) { return v; }
  return Math.ceil(Math.round(v * 1e9) / 1e9);
}

