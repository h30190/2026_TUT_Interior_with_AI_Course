function 找維度(單位) {
  var 名 = Object.keys(單位表);
  for (var i = 0; i < 名.length; i++) {
    if (Object.prototype.hasOwnProperty.call(單位表[名[i]], 單位)) { return 名[i]; }
  }
  return null;
}

/* 換算到(3, 'm', 'cm') === 300。單位不存在或跨維度一律拋錯——那是寫程式的人錯了，
   不是使用者輸入錯，不該默默回傳 NaN 讓它流到畫面上。 */
function 換算到(值, 從, 到) {
  var a = 找維度(從);
  var b = 找維度(到);
  if (!a) { throw new Error('不認得的單位：' + 從); }
  if (!b) { throw new Error('不認得的單位：' + 到); }
  if (a !== b) { throw new Error('不能跨維度換算：' + 從 + '（' + a + '）→ ' + 到 + '（' + b + '）'); }
  if (typeof 值 !== 'number' || !isFinite(值)) { throw new Error('換算的值必須是有限數字'); }
  return 值 * 單位表[a][從] / 單位表[a][到];
}

