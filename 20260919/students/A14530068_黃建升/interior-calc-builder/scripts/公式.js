function 計算(名稱, 輸入) {
  if (!公式[名稱]) {
    return { 過程: [], 值: {}, 註記: '',
             錯誤: [{ 欄位: null, 等級: '致命', 訊息: '沒有這個公式：' + 名稱 }] };
  }

  var 驗 = 驗證(名稱, 輸入);
  var 擋下 = 驗.filter(function (e) { return e.等級 === '錯誤'; });
  if (擋下.length) {
    return { 過程: [], 值: {}, 註記: '', 錯誤: 驗 };
  }

  var r;
  try {
    r = 公式[名稱].計算(輸入);
  } catch (e) {
    return { 過程: [], 值: {}, 註記: '',
             錯誤: [{ 欄位: null, 等級: '致命', 訊息: '計算時發生例外：' + e.message }] };
  }

  /* ── 出口關卡 ──
     驗證只看輸入是否有限，但有限的數字相乘仍可能溢位：
     1e308 × 3.305785 已經超過 Number.MAX_VALUE，結果是 Infinity。
     2026-10-03 自測掃出 11 個這類欄位，入口擋不住，所以出口要再攔一次。
     這道關卡不需要預先知道哪個欄位會爆，新增公式也自動適用。 */
  var 非有限 = Object.keys(r.值).filter(function (k) {
    return typeof r.值[k] === 'number' && !isFinite(r.值[k]);
  });
  /* 只看數值不夠。2026-10-03 王品洋交叉稽核 #6：值全部有限，
     顯示用的算式字串卻寫著 Infinity——守衛看值不看畫面。
     使用者看到的是字串，所以字串也要守。 */
  var 壞字串 = (r.過程 || []).filter(function (s) {
    return /NaN|Infinity|undefined/.test(String(s.標籤) + String(s.算式));
  }).map(function (s) { return s.標籤; });
  if (非有限.length || 壞字串.length) {
    return { 過程: [], 值: {}, 註記: '', 錯誤: [{
      欄位: null, 等級: '錯誤',
      訊息: '計算結果超出可計算範圍（' + 非有限.concat(壞字串).join('、') +
            '），請確認輸入單位是否填錯（例如把公分填成了公尺）'
    }] };
  }

  /* 公式自己的跨欄位檢核：錯誤就擋，提醒照常附上 */
  var 檢核 = r.檢核 || [];
  delete r.檢核;
  if (檢核.some(function (e) { return e.等級 === '錯誤'; })) {
    return { 過程: [], 值: {}, 註記: '', 錯誤: 驗.concat(檢核) };
  }

  r.錯誤 = 驗.concat(檢核);   /* 只剩提醒，不擋 */
  return r;
}

