      if (鋪貼面積 < 0) { 鋪貼面積 = 0; }
      var 單片面積 = ((i.磚長 + i.填縫 / 10) / 100) * ((i.磚寬 + i.填縫 / 10) / 100);
      var 片數 = 進位(鋪貼面積 / 單片面積 * (1 + i.損耗 / 100));
      var 箱數 = 進位(片數 / i.每箱片數);

