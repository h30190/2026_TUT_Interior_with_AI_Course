/* 邊界與跨欄位測試。跑法：node scripts/邊界與交叉.test.js

   2026-10-03 王品洋交叉稽核 #13 用變異測試量出：整套測試對 34 個有效變異抓到 32 個，
   漏掉的兩個都在「門檻值」上——合理範圍的 >= 改成 >、塗佈率上限 +1。
   沒有任何一條測試把數字放在門檻「剛好上」和「剛好外」。這支補的就是那個位置。

   同時把交叉稽核 #1／#3／#5／#6 寫成回歸測試：那幾條的共同點是
   「每一欄自己看都合法」或「數值對、畫面字串錯」，原本的測試結構上抓不到。 */
'use strict';

var 引擎 = require('./公式.js');
var 計算 = 引擎.計算;
var 規則 = 引擎.規則;

var 失敗 = 0, 總數 = 0;
function 驗(名稱, 條件, 說明) {
  總數++;
  if (!條件) { 失敗++; console.log('  失敗｜' + 名稱 + (說明 ? '　' + 說明 : '')); }
}

var 基準 = {
  油漆: { ping: 10, wallH: 2.8, perim: 200, openArea: 1, rate: 9, coats: 2, loss: 10 },
  窗簾: { 窗寬: 200, 窗高: 250, 倍數: 2, 幅寬: 150, 兩側收邊: 10, 上下摺邊: 20 },
  磁磚: { 長: 50, 寬: 50, 扣除: 0, 磚長: 60, 磚寬: 60, 填縫: 2, 損耗: 10, 每箱片數: 4 }
};
function 改(名稱, 欄, v) { var o = Object.assign({}, 基準[名稱]); o[欄] = v; return o; }
function 該欄(r, 欄, 字) {
  return (r.錯誤 || []).some(function (e) { return e.欄位 === 欄 && e.訊息.indexOf(字) !== -1; });
}

/* 門檻的標準答案另外寫一份在這裡，不從引擎讀。
   第一版直接讀 引擎.規則，結果把塗佈率上限改成 31 的變異照樣全過——
   測試跟著被測的程式一起變，等於自己驗自己。改門檻是政策決定，要兩邊一起改才算數。 */
var 門檻 = {
  油漆: { ping: [0.5, 500], wallH: [1.8, 6], perim: [2, 200], openArea: [0.1, 100],
          rate: [1, 30], coats: [1, 10], loss: [0, 100] },
  窗簾: { 窗寬: [30, 1000], 窗高: [30, 400], 倍數: [1, 4], 幅寬: [90, 320],
          兩側收邊: [0, 50], 上下摺邊: [0, 100] },
  磁磚: { 長: [0.3, 100], 寬: [0.3, 100], 扣除: [0, 1000], 磚長: [5, 300], 磚寬: [5, 300],
          填縫: [0, 30], 損耗: [0, 100], 每箱片數: [1, 200] }
};

/* ── A 合理範圍門檻：剛好在邊界上不提醒，剛好超出就提醒 ── */
console.log('── A 合理範圍門檻（每欄上下界各兩點）──');
Object.keys(規則).forEach(function (名稱) {
  Object.keys(規則[名稱]).forEach(function (欄) {
    var d = 規則[名稱][欄];
    if (!d.合理) { return; }
    var 釘 = (門檻[名稱] || {})[欄];
    驗(名稱 + '.' + 欄 + ' 的門檻有寫進本測試的標準答案', !!釘);
    if (!釘) { return; }
    var 低 = 釘[0], 高 = 釘[1];
    var 步 = d.整數 ? 1 : null;

    [低, 高].forEach(function (v) {
      if (v === 0) { return; }
      var r = 計算(名稱, 改(名稱, 欄, v));
      驗(名稱 + '.' + 欄 + ' = ' + v + '（界上）不提醒', !該欄(r, 欄, '超出常見範圍'),
         JSON.stringify(r.錯誤));
    });

    var 外 = [高 + (步 || 高 * 1e-6)];
    if (低 > 0) { 外.push(低 - (步 || 低 * 1e-6)); }
    外.forEach(function (v) {
      var r = 計算(名稱, 改(名稱, 欄, v));
      if (該欄(r, 欄, '不能小於') || 該欄(r, 欄, '必須大於')) { return; }   /* 低於硬下限，是錯誤不是提醒 */
      驗(名稱 + '.' + 欄 + ' = ' + v + '（界外）要提醒', 該欄(r, 欄, '超出常見範圍'),
         JSON.stringify(r.錯誤));
    });
  });
});

/* ── B 物理上限：剛好等於可以算，超過就擋 ── */
console.log('── B 物理上限（交叉稽核 #6 的入口防線）──');
Object.keys(規則).forEach(function (名稱) {
  Object.keys(規則[名稱]).forEach(function (欄) {
    var d = 規則[名稱][欄];
    驗(名稱 + '.' + 欄 + ' 有定義物理上限', typeof d.最大 === 'number');
    if (typeof d.最大 !== 'number') { return; }
    var r1 = 計算(名稱, 改(名稱, 欄, d.最大));
    驗(名稱 + '.' + 欄 + ' = 最大值不擋', !該欄(r1, 欄, '不能大於'));
    var r2 = 計算(名稱, 改(名稱, 欄, d.整數 ? d.最大 + 1 : d.最大 * 1.000001));
    驗(名稱 + '.' + 欄 + ' 超過最大值要擋', 該欄(r2, 欄, '不能大於'));
  });
});

/* ── C 交叉稽核回歸 ── */
console.log('── C 交叉稽核 #1／#3／#5／#6 回歸 ──');
var 油 = { ping: 10, wallH: 2.8, perim: 0, openArea: 6, rate: 9, coats: 2, loss: 10 };
function 油漆(o) { return 計算('油漆', Object.assign({}, 油, o)); }

var r = 油漆({ ping: 5, openArea: 50 });
驗('#1 開口 50 m² 大於 5 坪的牆面積：擋下', 該欄(r, 'openArea', '大於牆面總面積') && r.值.加侖數 === undefined,
   JSON.stringify(r));
r = 計算('磁磚', { 長: 2, 寬: 2, 扣除: 5, 磚長: 60, 磚寬: 60, 填縫: 2, 損耗: 10, 每箱片數: 4 });
驗('#1 同類：磁磚扣除面積大於總面積：擋下', 該欄(r, '扣除', '大於總面積') && r.值.箱數 === undefined);
r = 油漆({ perim: 10, wallH: 2.8, openArea: 28 });
驗('#1 開口剛好等於牆面積：提醒且結果 0', 該欄(r, 'openArea', '剛好等於') && r.值.加侖數 === 0);

r = 油漆({ ping: 50, perim: 10 });
驗('#3 50 坪配周長 10 m：提醒最短周長', 該欄(r, 'perim', '最短周長') && r.值.加侖數 > 0);
r = 油漆({ ping: 10, perim: 23 });
驗('#3 合理的周長不提醒', !該欄(r, 'perim', '最短周長'));

r = 油漆({ perim: 23, wallH: 9.24 * (10 / 33) });
var 字 = r.過程.map(function (s) { return s.算式; }).join(' ');
驗('#5 台尺換算的淨高在算式裡沒有浮點雜訊', !/\d\.\d{6,}/.test(字), 字);

[1e307, 1e306, 1.79e306, 99999.99].forEach(function (v) {
  var r = 油漆({ ping: v });
  var 全文 = JSON.stringify(r);
  驗('#6 地坪 ' + v + '：畫面與數值都沒有 Infinity／NaN', !/Infinity|NaN/.test(全文), 全文.slice(0, 200));
});
/* 出口關卡要看字串：把公式暫時換成「數值有限、字串是 Infinity」的版本，關卡必須擋下 */
var 原 = 引擎.公式.油漆.計算;
引擎.公式.油漆.計算 = function () {
  return { 過程: [{ 標籤: '測試', 算式: 'Infinity m²' }], 值: { 加侖數: 1 }, 註記: '' };
};
r = 油漆({});
引擎.公式.油漆.計算 = 原;
驗('#6 出口關卡會掃顯示字串', r.錯誤.some(function (e) { return e.訊息.indexOf('超出可計算範圍') !== -1; }),
   JSON.stringify(r.錯誤));

console.log('');
console.log(失敗 ? '共 ' + 失敗 + ' 項失敗（共 ' + 總數 + ' 項）' : '全部 ' + 總數 + ' 項通過');
process.exit(失敗 ? 1 : 0);
