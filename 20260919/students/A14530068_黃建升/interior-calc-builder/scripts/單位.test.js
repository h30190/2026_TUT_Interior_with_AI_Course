function 提醒文字(公式, 基準, 覆蓋) {
  var i = {};
  Object.keys(基準).forEach(function (k) { i[k] = 基準[k]; });
  Object.keys(覆蓋).forEach(function (k) { i[k] = 覆蓋[k]; });
  return (引擎.計算(公式, i).錯誤 || [])
    .filter(function (e) { return e.等級 === '提醒'; })
    .map(function (e) { return e.訊息; }).join('｜');
}
