var 單位字樣 = {
  m: ['公尺', 'm'],
  cm: ['公分', 'cm'],
  mm: ['公釐', 'mm', '釐米'],
  m2: ['m²', '平方公尺'],
  坪: ['坪']
};

var 設定目錄 = path.join(__dirname, '..', '設定');
fs.readdirSync(設定目錄).filter(function (f) { return f.endsWith('.json'); })
  .forEach(function (f) {
    var 設定 = JSON.parse(fs.readFileSync(path.join(設定目錄, f), 'utf8'));
    var 規 = 引擎.規則[設定.公式] || {};
    var 欄位 = (設定.輸入 || []).concat(設定.參數 || []);
    var 不符 = [];
    欄位.forEach(function (欄) {
      var d = 規[欄.id];
      if (!d || !d.單位) { return; }          /* 無單位的欄位不檢查 */
      var 字樣 = 單位字樣[d.單位];
      if (!字樣) { 不符.push(欄.id + ' 的單位 ' + d.單位 + ' 沒有對應字樣'); return; }
      var 有 = 字樣.some(function (s) { return 欄.標籤.indexOf(s) !== -1; });
      if (!有) {
        不符.push(欄.id + ' 標籤「' + 欄.標籤 + '」沒提到 ' + 字樣[0] +
                  '（引擎當成 ' + d.單位 + ' 算）');
      }
    });
    驗(f, 不符.length === 0, 不符.length ? 不符.join('；') : 欄位.length + ' 個欄位一致');
  });

