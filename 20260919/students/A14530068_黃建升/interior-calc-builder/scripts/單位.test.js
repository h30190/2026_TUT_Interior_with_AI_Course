var 失敗 = 0;
function 驗(名稱, 條件, 說明) {
  if (!條件) { 失敗++; }
  console.log('  ' + (條件 ? '通過' : '失敗') + '｜' + 名稱 + (說明 ? '　' + 說明 : ''));
}
function 近似(a, b) { return Math.abs(a - b) < 1e-9; }

